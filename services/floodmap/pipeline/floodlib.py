def impact_assets(site: dict, tr, shape, crs, ext):
    import geopandas as gpd
    from shapely.geometry import box
    from shapely.ops import substring
    imp = site["impacts"]
    osm = gpd.read_file(site["_root"] / imp["features"]).to_crs(crs)
    osm = osm[osm.intersects(box(ext[0], ext[2], ext[1], ext[3]))]
    hw = osm[osm.kind == "highway"]
    roads = hw[hw.highway.isin(imp.get("road_kinds", ["primary", "secondary", "tertiary", "residential", "unclassified", "trunk", "service"]))]
    nb = lambda d: d[d.bridge.isna()]
    lin = {}
    for nm in imp.get("linear", []):
        g = nb(hw[hw.name == nm])
        if len(g):
            lin[nm] = g.geometry.union_all()
    if imp.get("cross_streets", True):
        cr = nb(roads[roads.name.notna() & ~roads.name.isin(imp.get("linear", []))])
        lin.update({nm: g.geometry.union_all() for nm, g in cr.groupby("name")})
    rows = []
    for nm, g in lin.items():
        for ln in getattr(g, "geoms", [g]):
            n = max(int(ln.length // 15.0), 1)
            rows += [dict(name=nm, geometry=substring(ln, q * ln.length / n, (q + 1) * ln.length / n)) for q in range(n)]
    pieces = gpd.GeoDataFrame(rows, crs=crs) if rows else gpd.GeoDataFrame(columns=["name", "geometry"], crs=crs)
    area = osm[osm.kind.isin(["parking", "leisure"])]
    area = area[area.geometry.area > 50]
    bldg = osm[osm.kind == "building"]
    return dict(pieces=pieces, area=area, bldg=bldg, roads=roads, linear=list(imp.get("linear", [])))


def feature_cells(assets, tr, shape, base_mask):
    from rasterio.features import rasterize
    def cells(geom, buf):
        m = rasterize([(geom.buffer(buf), 1)], out_shape=shape, transform=tr, dtype="uint8").astype(bool) & ~base_mask
        return np.nonzero(m)
    return dict(pieces=[(r["name"], r.geometry.length, cells(r.geometry, 2.0)) for _, r in assets["pieces"].iterrows()],
                area=[(r.kind, (r["name"] if isinstance(r["name"], str) else ("parking lot" if r.kind == "parking" else str(r.leisure).replace("_", " "))),
                       cells(r.geometry, 0.0)) for _, r in assets["area"].iterrows()],
                bldg=[(r["name"] if isinstance(r["name"], str) else "", cells(r.geometry.exterior, 1.0)) for _, r in assets["bldg"].iterrows()])


def impacts(h, base_mask, fc, linear, wet_depth):
    """Impact summary of one depth map (maximum depth), US customary units."""
    wet = h > wet_depth
    frac = lambda c: float(wet[c].mean()) if len(c[0]) else 0.0
    length = {}
    for nm, L, c in fc["pieces"]:
        if frac(c) >= 0.5:
            length[nm] = length.get(nm, 0.0) + L
    lots = [(lab, float(np.percentile(h[c], 90))) for k, lab, c in fc["area"] if k == "parking" and frac(c) >= 0.25]
    parks = [(lab, float(np.percentile(h[c], 90))) for k, lab, c in fc["area"] if k == "leisure" and frac(c) >= 0.25]
    bl = [lab for lab, c in fc["bldg"] if len(c[0]) and wet[c].any()]
    out = {f"{nm}_ft": round(length.get(nm, 0.0) / FT) for nm in linear}
    out["cross_streets"] = sorted([dict(name=nm, length_ft=round(L / FT)) for nm, L in length.items() if nm not in linear],
                                  key=lambda r: -r["length_ft"])
    out["parking_lots"] = len(lots)
    out["parks_playgrounds"] = len(parks)
    out["buildings"] = len(bl)
    out["named_buildings"] = sorted({b for b in bl if b})
    out["flooded_acres_outside_creek"] = round(float((wet & ~base_mask).sum()) * 1.0 / 4046.86, 1)
    return out


# ---------------------------------------------------------------------------------------------- map image
def render_map(png: Path, z, hmax, tr, ext, assets, title: str, subtitle: str, wet_depth=0.15, gauge_xy=None):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LightSource, LinearSegmentedColormap
    cmap = LinearSegmentedColormap.from_list("flood", ["#c6e6f7", "#6fb7e3", "#2b7bba", "#16508f", "#0b2a5c"])
    h, w = z.shape
    fig_h = 9.0
    fig, ax = plt.subplots(figsize=(fig_h * w / h + 1.6, fig_h), constrained_layout=True)
    ax.imshow(LightSource(azdeg=315, altdeg=45).hillshade(z, vert_exag=2, dx=tr.a, dy=-tr.e), cmap="gray", extent=ext, vmin=0, vmax=1.2)
    if len(assets["bldg"]):
        assets["bldg"].plot(ax=ax, color="#5a5a5a", lw=0)
    if len(assets["roads"]):
        assets["roads"].plot(ax=ax, color="white", lw=0.7)
    im = ax.imshow(np.where(hmax > wet_depth, hmax / FT, np.nan), cmap=cmap, extent=ext, vmin=0, vmax=10, alpha=0.9)
    if gauge_xy:
        ax.plot(*gauge_xy, "r^", ms=8, mec="k")
    ax.set_xlim(ext[0], ext[1]); ax.set_ylim(ext[2], ext[3]); ax.set_xticks([]); ax.set_yticks([])
    fig.colorbar(im, ax=ax, shrink=0.45, label="maximum water depth (ft)")
    ax.set_title(f"{title}\n{subtitle}", fontsize=10)
    fig.savefig(png, dpi=110)
    plt.close(fig)
