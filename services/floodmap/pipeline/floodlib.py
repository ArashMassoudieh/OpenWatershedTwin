"""Site-independent pieces of the flood-map job runner (run_job.py): run windows, 2D-DWE configs, hot starts,
impacts and the map image. Everything site-specific comes from the site file (services/floodmap/sites/<site>.json).

The rules follow the Sligo Creek flood2d pipeline (Sligo Creek/flood2d/scripts 04_make_run.py, 05_products.py,
12_map_library.py), from which they were generalised:
  - inflow edge = sum of its links times their fractions; point sources = their link times their fraction;
  - a road/trail piece (15 m) is under water when >= 50 % of its cells outside the in-bank creek are > wet_depth_m;
    an area feature when >= 25 % of its area is; a building when water > wet_depth_m touches it (1 m ring);
  - the in-bank creek is the water when the model gauge first reaches the site's in-bank stage (NWS action stage),
    or the hot-start water if it never does.
"""
import json
import math
import os
from pathlib import Path

import numpy as np
import pandas as pd

EPOCH = pd.Timestamp("1899-12-30", tz="UTC")
FT = 0.3048
CFS = 0.0283168466


def load_site(sites_dir: Path, name: str) -> dict:
    s = json.loads((sites_dir / f"{name}.json").read_text())
    root = Path(s.get("data_root", sites_dir))
    s["_root"] = root
    s["_sources"] = json.loads((root / s["sources"]).read_text())
    return s


def member_frame(member: dict) -> pd.DataFrame:
    """A request member {"t_utc": [...], "links": {name: [...]}} as a DataFrame indexed by UTC time (m3/s)."""
    df = pd.DataFrame(member["links"], index=pd.DatetimeIndex(pd.to_datetime(member["t_utc"], utc=True)))
    return df.sort_index()


def run_window(df: pd.DataFrame, site: dict) -> tuple:
    """(start, end) of the 2D run: from LEAD_H before the rising limb leaves LOW_FRAC x threshold at the trigger link,
    to TAIL_H after it falls back below the threshold, at most MAX_H long."""
    w = site["window"]
    q = df[w["trigger_link"]]
    thr = float(w["threshold_cms"])
    tpk = q.idxmax()
    rising = q[:tpk][q[:tpk] < w.get("low_frac", 0.3) * thr]
    start = (rising.index[-1] if len(rising) else q.index[0]) - pd.Timedelta(hours=w.get("lead_h", 2.0))
    start = max(start, q.index[0]).floor("15min")
    after = q[tpk:][q[tpk:] < thr]
    end = (after.index[0] if len(after) else q.index[-1]) + pd.Timedelta(hours=w.get("tail_h", 3.0))
    end = min(end, q.index[-1], start + pd.Timedelta(hours=w.get("max_h", 12.0)))
    return start, end


def hydrographs(df: pd.DataFrame, site: dict, start, end, dt_s=300.0) -> tuple:
    """(t_s grid, inflow edge series, {point source: series}) on a regular grid from start, m3/s."""
    info = site["_sources"]
    t = np.arange(0.0, (end - start).total_seconds() + dt_s + 1e-6, dt_s)
    x = (df.index - start).total_seconds().to_numpy()
    lin = lambda col: np.interp(t, x, df[col].to_numpy())
    edge = info["inflow"].get("links", {info["inflow"]["link"]: 1.0})
    q_in = sum(f * lin(l) for l, f in edge.items())
    pts = {n: s["fraction"] * lin(s.get("link", n)) for n, s in info["sources"].items()}
    return t, np.maximum(q_in, 0.0), {n: np.maximum(v, 0.0) for n, v in pts.items()}


def write_bc(path: Path, t, q, note: str):
    with open(path, "w") as f:
        f.write(f"# {note}\nt_s,Q_cms\n")
        f.writelines(f"{a:.1f},{b:.5f}\n" for a, b in zip(t, q))


def choose_hotstart(site: dict, q0: float):
    """The pre-built base-flow state nearest in log flow to the inflow at the window start (None if no library)."""
    hs = site.get("hotstart")
    if not hs:
        return None, None
    d = site["_root"] / hs["dir"]
    idx = json.loads((d / "index.json").read_text())
    lvl = min(idx["levels"], key=lambda l: abs(math.log(max(l["q_cms"], 1e-4) / max(q0, 1e-4))))
    return d / lvl["file"], lvl


def config_text(site: dict, name: str, start, t_end_s: float, inflow_csv: Path, points: dict, h0, t_out: float) -> str:
    info, root = site["_sources"], site["_root"]
    lines = [f"# {site['label']}: flood-map service job, generated by floodlib.config_text",
             f"name      {name}",
             f"dem       {root / site['dem']}",
             f"manning   {root / site['manning']}",
             f"crs       {site.get('crs', info['crs'])}",
             f"time0     {start.isoformat()}",
             f"t_end     {t_end_s:.0f}",
             f"t_out     {t_out:.0f}",
             "t_gauge   300",
             f"cfl       {site.get('cfl', 0.7)}",
             f"theta     {site.get('theta', 0.9)}",
             "dt_max    5",
             f"n_default {site.get('n_default', 0.06)}",
             f"flood_h   {site['impacts'].get('wet_depth_m', 0.15)}",
             "frames    depth",
             "vti       0",
             f"inflow_conveyance {info['inflow']['side']} {info['inflow']['cells'][0]} {info['inflow']['cells'][1]} {inflow_csv}",
             f"outfall   {info['outfall']['side']} 0 -1 {info['outfall']['slope']:.5f}"]
    if h0:
        lines.append(f"h0        {h0}")
    lines += [f"point     {n} {info['sources'][n]['i']} {info['sources'][n]['j']} {p}" for n, p in points.items()]
    lines += [f"gauge     {n} {g['i']} {g['j']}" for n, g in gauge_cells(site).items()]
    return "\n".join(lines) + "\n"


def gauge_cells(site: dict) -> dict:
    """Model gauge cells: on the site's thalweg, upstream_m above the gauge's nearest thalweg point (the pool above
    its control), as 04_make_run.py does."""
    th = pd.read_csv(site["_root"] / site["thalweg"])
    out = {}
    for name, g in site.get("gauges", {}).items():
        gi = site["_sources"]["gauges"][g["sources_key"]]
        k = int(np.argmin(np.hypot(th.x - gi["x"], th.y - gi["y"])))
        s0 = float(th.s_m[k]) - float(g.get("upstream_m", 10.0))
        k2 = int(np.argmin(abs(th.s_m - s0)))
        out[name] = dict(i=int(th.i[k2]), j=int(th.j[k2]))
    return out


